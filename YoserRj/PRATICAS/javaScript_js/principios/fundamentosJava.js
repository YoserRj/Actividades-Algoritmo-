// TIPOS DE DATOS JAVASCRIPT
// aprendiendo variable 
// hay tres const, var y let

let nombre = "Yoser rojas"; // variable de tipo string
let edad = 21 ; // variable de tipo int
let cantidad = 1.500000; // variable de tipo float
let precio = 15.5;  
let verdadero = true; // variable de tipo boolean
let falso = false; // variable de tipo boolean
let nulo = null; // variable de tipo vacio

// formas de concatenar o juntar variables y tipo de datos.

console.log(nombre + " " + edad + " " + cantidad + " " + precio + " " + verdadero + " " + falso + " " + nulo); // concatencion de mas y comillas
console.log(nombre, + " " + edad, + " " + cantidad, + " " + precio, + " " + verdadero, + " " + falso, + " " + nulo); // concatenacion de mas y comas
console.log(`${nombre} ${edad} ${cantidad} ${precio} ${verdadero} ${falso} ${nulo}`); // concatenacion dentro de letas
console.log(`${nombre}\n ${edad}\n ${cantidad}\n ${precio}\n ${verdadero}\n ${falso}\n ${nulo}`); // salto de lineas en imprimir
