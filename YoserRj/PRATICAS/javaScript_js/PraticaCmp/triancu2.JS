// ===================
//Ejercicio 1 - Area de un triángulo
// Fórmula: AT = (B * H) /2
// AT = area del triángulo
// B = Base
// H = Altura
// ==================

// cambiar los valores para el progama con otro datos.

const base = 10; // base del triángulo (Número)
const altura = 4; // altura del triángulo (Número)

// aplicamos la formula del aréa: (base por altura dicidido entre 2)
const areaTriangulo = (base * altura) / 2;

// mostramos en consola los datos de entrada junto al resultado obtenido.
console.log("==== Área del triángulo:");
console.log("La base es: ", base); // imprime el valor de la base
console.log("La altura es: ", altura); // imprime el valor de la altura
console.log("El área del triángulo es: ", areaTriangulo); // imprime el Resultado final.    

